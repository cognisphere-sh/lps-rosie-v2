BEGIN NEW.updated_at := now(); RETURN NEW; END $$;
CREATE TABLE public.suppliers (id bigint PRIMARY KEY, is_active boolean NOT NULL DEFAULT true,
  is_lps_partner boolean NOT NULL DEFAULT true);
CREATE TABLE public.job_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  status text NOT NULL DEFAULT 'sourcing' CONSTRAINT job_requests_status_check CHECK (
    status IN ('sourcing', 'quoted', 'availability', 'confirmed', 'closed_won', 'closed_lost', 'archived')),
  is_active boolean NOT NULL DEFAULT true
);
CREATE TABLE public.job_request_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_request_id bigint NOT NULL REFERENCES public.job_requests(id) ON DELETE CASCADE,
  name text NOT NULL DEFAULT 'Oak', size text, quantity numeric CHECK (quantity > 0), unit_price numeric,
  is_active boolean NOT NULL DEFAULT true, status text NOT NULL DEFAULT 'pending'
);
CREATE TABLE public.availability_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_request_id bigint NOT NULL REFERENCES public.job_requests(id) ON DELETE CASCADE,
  supplier_id bigint NOT NULL REFERENCES public.suppliers(id),
  share_customer_details boolean NOT NULL DEFAULT false,
  is_active boolean NOT NULL DEFAULT true,
  status text NOT NULL DEFAULT 'new' CHECK (status IN ('new','processing','submitted','closed')),
  submitted_at timestamptz, created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.availability_request_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  availability_request_id bigint NOT NULL REFERENCES public.availability_requests(id) ON DELETE CASCADE,
  job_request_item_id bigint REFERENCES public.job_request_items(id) ON DELETE SET NULL,
  name text NOT NULL, size text, quantity numeric CHECK (quantity > 0),
  status text CHECK (status IN ('available','unavailable','can_order','diff_size_qty_sub','arriving_soon')),
  available_quantity numeric, unit_price numeric, notes text, lps_notes text, mapped_inventory_id uuid,
  is_active boolean NOT NULL DEFAULT true
);
