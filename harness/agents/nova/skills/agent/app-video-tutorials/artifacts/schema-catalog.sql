-- Read-only catalog queries that regenerate video/partner-onboarding/demo/schema.sql
-- from the live database's STRUCTURE (no rows). Run each against production
-- (Supabase connector / read-only SQL), paste the output into the matching
-- section of schema.sql, load it into the local demo stack, then run query 5
-- on both databases and compare. `*_pre_0NNN` backup tables are skipped.

-- 1. Tables: columns, identity, generated columns, defaults, NOT NULL.
select string_agg(ddl, E'\n' order by relname) from (
  select c.relname, 'create table public.' || quote_ident(c.relname) || ' (' || E'\n  ' ||
    string_agg(quote_ident(a.attname) || ' ' || format_type(a.atttypid, a.atttypmod)
      || case when a.attidentity = 'a' then ' generated always as identity' when a.attidentity = 'd' then ' generated by default as identity' else '' end
      || case when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(d.adbin, d.adrelid) || ') stored'
              when d.adbin is not null and a.attidentity = '' then ' default ' || pg_get_expr(d.adbin, d.adrelid) else '' end
      || case when a.attnotnull then ' not null' else '' end, E',\n  ' order by a.attnum) || E'\n);' ddl
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  join pg_attribute a on a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped
  left join pg_attrdef d on d.adrelid = c.oid and d.adnum = a.attnum
  where n.nspname = 'public' and c.relkind in ('r', 'p') and c.relname !~ '_pre_0'
  group by c.relname) t;

-- 2. Constraints (PK, unique, check, FK), non-constraint indexes, views, triggers,
--    RLS, policies, storage buckets, realtime publication.
with rels as (select c.oid, c.relname, c.relkind, c.relrowsecurity from pg_class c join pg_namespace n on n.oid = c.relnamespace
              where n.nspname = 'public' and c.relname !~ '_pre_0' and c.relkind in ('r', 'p', 'v'))
select
 (select string_agg('alter table public.' || quote_ident(r.relname) || ' add constraint ' || quote_ident(co.conname) || ' ' || pg_get_constraintdef(co.oid) || ';', E'\n'
    order by case co.contype when 'p' then 0 when 'u' then 1 when 'c' then 2 else 3 end, r.relname, co.conname)
  from pg_constraint co join rels r on r.oid = co.conrelid where co.contype in ('p', 'u', 'c', 'f', 'x')) as constraints,
 (select string_agg(pg_get_indexdef(i.indexrelid) || ';', E'\n' order by r.relname) from pg_index i join rels r on r.oid = i.indrelid
  where not exists (select 1 from pg_constraint co where co.conindid = i.indexrelid and co.contype in ('p', 'u', 'x'))) as indexes,
 (select string_agg('create view public.' || quote_ident(r.relname) || coalesce(' with (' || array_to_string(c.reloptions, ',') || ')', '') || ' as ' || pg_get_viewdef(r.oid), E'\n')
  from rels r join pg_class c on c.oid = r.oid where r.relkind = 'v') as views,
 (select string_agg(pg_get_triggerdef(t.oid) || ';', E'\n' order by c.relname, t.tgname) from pg_trigger t join pg_class c on c.oid = t.tgrelid
  join pg_namespace n on n.oid = c.relnamespace where n.nspname = 'public' and not t.tgisinternal and c.relname !~ '_pre_0') as triggers,
 (select string_agg('alter table public.' || quote_ident(relname) || ' enable row level security;', E'\n') from rels where relrowsecurity) as rls,
 (select string_agg(format('create policy %I on %I.%I as %s for %s to %s%s%s;', policyname, schemaname, tablename, permissive, cmd,
    array_to_string(roles, ','), coalesce(' using (' || qual || ')', ''), coalesce(' with check (' || with_check || ')', '')), E'\n')
  from pg_policies where schemaname in ('public', 'storage')) as policies,
 (select string_agg(id || ' public=' || public || ' limit=' || coalesce(file_size_limit::text, '-') || ' mimes=' || coalesce(array_to_string(allowed_mime_types, ','), '-'), E'\n')
  from storage.buckets) as buckets,
 (select string_agg(schemaname || '.' || tablename, ' ') from pg_publication_tables where pubname = 'supabase_realtime') as realtime;

-- 3. Function names (pick which to take from migrations with scripts/extract-functions.py).
select string_agg(p.proname, ',' order by p.proname) from pg_proc p join pg_namespace n on n.oid = p.pronamespace
where n.nspname = 'public' and p.prokind in ('f', 'p') and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e');

-- 4. Live definition of the functions that are missing from the migrations or differ (edit the list).
select string_agg(pg_get_functiondef(p.oid), E';\n\n' order by p.proname) from pg_proc p join pg_namespace n on n.oid = p.pronamespace
where n.nspname = 'public' and p.proname in ('normalize_plant_key', 'normalize_search_text');

-- 5. Compare: run on production and on the local demo DB, then diff.
select string_agg(p.proname || '=' || md5(p.prosrc), ' ' order by p.proname) from pg_proc p join pg_namespace n on n.oid = p.pronamespace
where n.nspname = 'public' and p.prokind in ('f', 'p') and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e');
